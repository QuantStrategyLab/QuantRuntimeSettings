import assert from 'node:assert/strict';
import { aggregateEquity, alignReturns, chainReturns, cleanPoints, rebase, rangeStart, sliceRange } from '../web/strategy-switch-console/frontend/src/performanceMath.ts';
const p = (date, value, externalFlow = null) => ({ date, value, externalFlow });
const close = (actual, expected) => assert.ok(Math.abs(actual - expected) < 1e-9, `${actual} != ${expected}`);
const account = [p('2026-01-01', 100, 0), p('2026-01-02', 110, 0), p('2026-01-03', 210, 100), p('2026-01-04', 168, -42)];
const twr = chainReturns(account);
assert.equal(twr.unknownFlow, false);
assert.equal(twr.invalidPeriod, false);
close(rebase(twr.index).at(-1).value, 10);
assert.deepEqual(chainReturns([p('2026-01-01',100),p('2026-01-02',200,100)]).index.map(p=>p.value), [1,1], 'deposit does not create return');
assert.deepEqual(chainReturns([p('2026-01-01',100),p('2026-01-02',60,-40)]).index.map(p=>p.value), [1,1], 'withdrawal does not destroy return');
assert.equal(chainReturns([p('2026-01-01',100),p('2026-01-02',200)]).unknownFlow,true);
assert.equal(chainReturns([p('2026-01-01',0),p('2026-01-02',100,0)]).invalidPeriod,true);
assert.equal(chainReturns([p('2026-01-01',100),p('2026-01-02',-1,0)]).invalidPeriod,true);
assert.deepEqual(chainReturns([]).index, []);
assert.deepEqual(rebase(chainReturns([p('2026-01-01',100)]).index).map(p=>p.value),[0]);
assert.deepEqual(rebase([]),[]);
assert.deepEqual(rebase([p('2026-01-01',0)]),[]);
close(rebase([p('2026-01-01',100),p('2026-01-02',110)], '2026-01-02')[0].value,0);
const aggregate = aggregateEquity([{id:'a',points:account},{id:'b',points:account.map(p=>({...p,value:p.value*2,externalFlow:p.externalFlow*2}))}]);
assert.equal(aggregate.points[2].value,630);
assert.equal(aggregate.points[2].externalFlow,300);
close(rebase(chainReturns(aggregate.points).index).at(-1).value,10);
const weighted = aggregateEquity([{id:'a',points:[p('2026-01-01',100,0),p('2026-01-02',110,0)]},{id:'b',points:[p('2026-01-01',300,0),p('2026-01-02',300,0)]}]);
close(rebase(chainReturns(weighted.points).index).at(-1).value,2.5,'capital weighted, not average account percentages');
const partial = aggregateEquity([{id:'a',points:account},{id:'b',points:[account[0],account[2]]},{id:'missing',points:[]}]);
assert.deepEqual(partial.missingAccounts,['missing']);
assert.equal(partial.omittedDates,2);
assert.equal(partial.points[1].breakBefore,true);
assert.equal(partial.points[1].externalFlow,null,'flow coverage across skipped cohort dates cannot be assumed');
assert.deepEqual(aggregateEquity([]).points,[]);
const aligned = alignReturns(twr.index,[{id:'late',points:[p('2026-01-02',50),p('2026-01-04',55)]},{id:'early',points:[p('2026-01-01',100),p('2026-01-02',100),p('2026-01-03',110),p('2026-01-04',120)]}]);
assert.equal(aligned.start,'2026-01-02');
for(const s of [aligned.primary,...aligned.benchmarks.map(s=>s.points)]) assert.equal(s[0].value,0,'all series start at exactly zero on common date');
assert.deepEqual(aligned.benchmarks[0].points.map(p=>p.date),['2026-01-02','2026-01-04']);
assert.equal(aligned.benchmarks[0].points[1].breakBefore,false,'weekend-only gaps connect on the common observed axis');
assert.deepEqual(aligned.primary.map(point=>point.date),aligned.benchmarks[0].points.map(point=>point.date));
assert.equal(alignReturns(twr.index,[{id:'no-overlap',points:[p('2025-01-01',1)]}]).noCommonDate,true);
assert.equal(alignReturns(twr.index,[]).primary[0].value,0);
assert.deepEqual(alignReturns([],[]).primary,[]);
assert.deepEqual(cleanPoints([p('invalid',5),p('2026-02-30',1),p('2026-01-01',1),p('2026-01-01',2)]),[]);
assert.equal(rangeStart('1m','2026-03-31'),'2026-02-28');
assert.equal(rangeStart('3m','2026-05-31'),'2026-02-28');
assert.equal(rangeStart('1y','2024-02-29'),'2023-02-28');
assert.equal(rangeStart('ytd','2026-10-15'),'2026-01-01');
const boundaries = { '1m':'2026-09-15', '3m':'2026-07-15', ytd:'2026-01-01', '1y':'2025-10-15', all:'2020-01-01' };
for (const [range, start] of Object.entries(boundaries)) {
  const before = new Date(Date.parse(start+'T00:00:00Z')-86400000).toISOString().slice(0,10);
  const rows = sliceRange([p(before,1),p(start,2),p('2026-10-15',3),p('2026-10-16',4)],range,'2026-10-15');
  assert.deepEqual(rows.map(p=>p.date),range==='all'?[before,start,'2026-10-15']:[start,'2026-10-15']);
  assert.deepEqual(sliceRange([],range,'2026-10-15'),[]);
}
console.log('console_performance_math_validation: PASS (rebasing, alignment, gaps, deposits, withdrawals, weighted multi-account TWR, unknown flows, empty/single, all range boundaries; synthetic only)');
