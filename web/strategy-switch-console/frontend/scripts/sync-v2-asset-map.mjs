import { readdir, readFile, writeFile } from "node:fs/promises";
import { extname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const frontendRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const preview = process.argv.includes("--preview");
if (process.argv.slice(2).some(argument => argument !== "--preview")) throw new Error("unsupported asset-map option");
const namespace = preview ? "preview" : "v2";
const exportPrefix = preview ? "PREVIEW" : "V2";
const distRoot = join(frontendRoot, preview ? "dist-preview" : "dist");
const output = resolve(frontendRoot, "..", `${namespace}_asset_map.js`);
const mimeByExtension = new Map([
  [".css", "text/css; charset=utf-8"],
  [".js", "text/javascript; charset=utf-8"],
  [".png", "image/png"],
]);

async function walk(directory) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) found.push(...await walk(path));
    else if (entry.isFile()) found.push(path);
  }
  return found;
}

const files = (await walk(distRoot)).sort();
const htmlPath = join(distRoot, "index.html");
if (!files.includes(htmlPath)) throw new Error("frontend dist is missing index.html; run npm run build first");
const resources = files.filter(path => path !== htmlPath);
if (!resources.some(path => path.endsWith("/qsl-brand-icon.png"))) throw new Error("frontend dist is missing qsl-brand-icon.png");
const entries = [];
for (const path of resources) {
  const name = path.slice(distRoot.length + 1).split("\\").join("/").replace(/^assets\//, "");
  if (name.startsWith("../") || name.includes("/../")) throw new Error("invalid dist resource path");
  const extension = extname(name).toLowerCase();
  const contentType = mimeByExtension.get(extension);
  if (!contentType) throw new Error(`unsupported v2 asset type: ${name}`);
  const bytes = await readFile(path);
  entries.push(`  ${JSON.stringify(`/${namespace}/assets/${name}`)}: { contentType: ${JSON.stringify(contentType)}, base64: ${JSON.stringify(bytes.toString("base64"))} },`);
}
const html = await readFile(htmlPath, "utf8");
if (preview && (/\/(?:v2)\//.test(html) || !html.includes('/preview/assets/'))) throw new Error("preview HTML must use the independent /preview/assets/ base");
if (/<script[^>]*>[^<]/i.test(html) || /<style[^>]*>[^<]/i.test(html)) throw new Error("v2 shell must not contain inline scripts or styles");
const source = [
  "// Generated by frontend/scripts/sync-v2-asset-map.mjs; do not edit.",
  `export const ${exportPrefix}_PAGE_HTML = ${JSON.stringify(html)};`,
  `export const ${exportPrefix}_ASSETS = Object.freeze({`,
  ...entries,
  "});",
  "",
].join("\n");
await writeFile(output, source, "utf8");
console.log(`Generated ${entries.length} ${namespace} assets (${Buffer.byteLength(source)} bytes source) at ${output}`);
