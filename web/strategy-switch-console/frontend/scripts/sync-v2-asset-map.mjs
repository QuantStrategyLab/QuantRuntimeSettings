import { createHash } from "node:crypto";
import { readdir, readFile, writeFile } from "node:fs/promises";
import { extname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { validateV2Assets } from "./validate-v2-assets.mjs";

const frontendRoot = resolve(fileURLToPath(new URL("..", import.meta.url)));
const distRoot = join(frontendRoot, "dist");
const output = resolve(frontendRoot, "..", "v2_asset_map.js");
const mimeByExtension = new Map([
  [".css", "text/css; charset=utf-8"],
  [".js", "text/javascript; charset=utf-8"],
  [".png", "image/png"],
  [".svg", "image/svg+xml"],
]);

async function walk(directory) {
  const found = [];
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) found.push(...await walk(path));
    else if (entry.isFile()) found.push(path);
  }
  return found;
}

const files = (await walk(distRoot)).sort();
const htmlPath = join(distRoot, "index.html");
if (!files.includes(htmlPath)) throw new Error("frontend dist is missing index.html; run npm run build first");
const resources = files.filter(path => path !== htmlPath);
if (!resources.some(path => path.endsWith("/qsl-brand-icon.svg"))) throw new Error("frontend dist is missing qsl-brand-icon.svg");
const entries = [];
const assets = {};
for (const path of resources) {
  const name = path.slice(distRoot.length + 1).split("\\").join("/").replace(/^assets\//, "");
  if (name.startsWith("../") || name.includes("/../")) throw new Error("invalid dist resource path");
  const extension = extname(name).toLowerCase();
  const contentType = mimeByExtension.get(extension);
  if (!contentType) throw new Error(`unsupported v2 asset type: ${name}`);
  const bytes = await readFile(path);
  assets[`/v2/assets/${name}`] = { contentType, base64: bytes.toString("base64") };
  entries.push(`  ${JSON.stringify(`/v2/assets/${name}`)}: { contentType: ${JSON.stringify(contentType)}, base64: ${JSON.stringify(bytes.toString("base64"))} },`);
}
const html = await readFile(htmlPath, "utf8");
validateV2Assets(html, assets);
if (/<script[^>]*>[^<]/i.test(html) || /<style[^>]*>[^<]/i.test(html)) throw new Error("v2 shell must not contain inline scripts or styles");
const buildId = createHash("sha256").update(JSON.stringify({ html, assets })).digest("hex");
const source = [
  "// Generated by frontend/scripts/sync-v2-asset-map.mjs; do not edit.",
  `export const V2_BUILD_ID = ${JSON.stringify(buildId)};`,
  `export const V2_PAGE_HTML = ${JSON.stringify(html)};`,
  "export const V2_ASSETS = Object.freeze({",
  ...entries,
  "});",
  "",
].join("\n");
await writeFile(output, source, "utf8");
console.log(`Generated ${entries.length} v2 assets (${Buffer.byteLength(source)} bytes source) at ${output}`);
