export type CopyKey = keyof typeof EN_COPY;
export type Language = "zh" | "en";
export type LocaleMessage = { key: string; values?: Record<string, string | number | LocaleMessage> };
export const LocaleContext = createContext<Language>("zh");

const MISSING_COPY = "Information unavailable";

export function translate(key: CopyKey | string, language: Language, values: Record<string, string | number> = {}): string {
  const template = language === "zh" ? key : (EN_COPY as Record<string, string>)[key] || MISSING_COPY;
  return template.replace(/\{([A-Za-z][A-Za-z0-9_]*)\}/g, (_match, name: string) => Object.hasOwn(values, name) ? String(values[name]) : "");
}

export function formatAccountCount(count: number, language: Language): string {
  const key = language === "zh" ? "{count} 个账户" : count === 1 ? "{count} account" : "{count} accounts";
  return translate(key, language, { count });
}

export function renderLocaleMessage(message: LocaleMessage, language: Language): string {
  const values: Record<string,string|number> = {};
  for (const [name, value] of Object.entries(message.values || {})) {
    values[name] = typeof value === "object" ? renderLocaleMessage(value, language) : value;
  }
  return translate(message.key, language, values);
}

export function useT(): (key: CopyKey | string, values?: Record<string, string | number>) => string {
  const language = useContext(LocaleContext);
  return (key, values = {}) => translate(key, language, values);
}
export function useLocale(): Language { return useContext(LocaleContext); }
