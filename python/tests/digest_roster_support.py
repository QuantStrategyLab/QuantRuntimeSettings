"""Synthetic peers for the digest-roster core tests.

The B2 readbacks come from the committed corpus generated by the landed B2
builder (tests/digest_roster_b2_corpus.mjs). Authentication, transport and the
protected enrollment source are synthetic test peers. Every socket is trapped:
a test that reaches the network fails.
"""
from __future__ import annotations

import hashlib
import json
import socket
import sys
from copy import deepcopy
from datetime import UTC, datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / 'python' / 'scripts'))

import digest_roster_authority as authority  # noqa: E402

CORPUS = json.loads((ROOT / 'python/tests/fixtures/digest_roster_b2_corpus.json').read_text(encoding='utf-8'))
FIXTURE = json.loads((ROOT / 'tests/fixtures/account-mapping-roster.synthetic.json').read_text(encoding='utf-8'))
OBSERVED = datetime.fromisoformat(CORPUS['observed_at'].replace('Z', '+00:00'))
ORIGIN = 'https://console.example.invalid'
SOURCE = 'synthetic-enrollment'
AUDIENCE = 'synthetic-audience'
POLICY = authority.ServiceAuthPolicy('synthetic-issuer', AUDIENCE, frozenset({'synthetic-digest-reader'}))
BOOT = authority.RosterBootConfig(authority.MAPPING_MODE, ORIGIN, POLICY, SOURCE, 'synthetic_context')
VERSIONS = {'version': 'v1', 'membership_version': 'm1', 'label_version': 'l1', 'link_version': 'k1'}


class OutboundTrap:
    """Reject every socket connection for the duration of a test."""

    def __init__(self):
        self.attempts = 0

    def __enter__(self):
        self._connect, self._create = socket.socket.connect, socket.create_connection

        def refuse(*_args, **_kwargs):
            self.attempts += 1
            raise AssertionError('outbound network call attempted')
        socket.socket.connect = refuse
        socket.create_connection = refuse
        return self

    def __exit__(self, *_exc):
        socket.socket.connect, socket.create_connection = self._connect, self._create
        return False


def scenario(name):
    return deepcopy(CORPUS['scenarios'][name])


def preparation(name):
    return deepcopy(CORPUS['preparations'][name])


def at(document, instant):
    """A readback re-stamped as observed at `instant` (a server time)."""
    result = deepcopy(document)
    result['observed_at'] = instant if isinstance(instant, str) else stamp(instant)
    return result


def stamp(value):
    return value.astimezone(UTC).isoformat(timespec='milliseconds').replace('+00:00', 'Z')


def body(document):
    return json.dumps(document).encode('utf-8')


class SyntheticAuth:
    """A protected-source authenticator test peer issuing a fixed assertion."""

    def __init__(self, **overrides):
        self.overrides = overrides
        self.calls = 0

    def assertion(self, method, path, audience, clock):
        self.calls += 1
        values = {'token': 'synthetic-token', 'issuer': POLICY.issuer, 'audience': audience,
                  'subject': 'synthetic-digest-reader', 'expires_at': clock + timedelta(minutes=5),
                  'method': method, 'path': path, **self.overrides}
        return authority.ServiceAssertion(**values)


class SyntheticTransport:
    """Answers the management read from a queue of (status, headers, body)."""

    def __init__(self, *responses, url=None):
        self.responses = list(responses)
        self.requests = []
        self.url = url

    def get(self, url, headers, timeout):
        self.requests.append({'url': url, 'headers': dict(headers), 'timeout': timeout})
        response = self.responses.pop(0)
        if isinstance(response, BaseException):
            raise response
        if callable(response):
            response = response()
        status, headers_out, payload = response
        return authority.TransportResponse(status, headers_out, payload, self.url or url)


OK_HEADERS = {'content-type': 'application/json; charset=utf-8', 'cache-control': 'private, no-store'}


def ok(document):
    return 200, dict(OK_HEADERS), body(document)


def legacy_roster(links=None, profile='syn_profile'):
    """A protected legacy roster matching the fixture's links exactly."""
    return [{'platform_id': link['platform_id'], 'candidate_slot': link['candidate_slot'],
             'opaque_account_uid': link['opaque_account_uid'], 'target_id': link['target_id'],
             'strategy_profile': f'{profile}_{index}'}
            for index, link in enumerate(links if links is not None else FIXTURE['enrollment_links'])]


def instances():
    return deepcopy(FIXTURE['instances'])


def observation_bindings(readback, *, skip=()):
    """One typed observation binding per group whose scope is paper or live."""
    bindings = []
    for index, group in enumerate(readback['groups']):
        if group['scope'] not in {'paper', 'live'} or index in skip:
            continue
        deployment = group['deployments'][0]
        bindings.append({'binding_id': f'obs-{index:02d}', 'platform': deployment['platform'],
                         'legacy_key': deployment['key'], 'opaque_account_uid': None,
                         'broker_environment': group['scope'], 'account_scope': 'account'})
    return bindings


def prepare(name='complete', *, readback=None, projection=None, links=None, roster=None, bindings=None,
            effective=None, versions=None, instance_rows=None):
    prepared = preparation(name)
    live = readback if readback is not None else prepared['readback']
    return authority.prepare_enrollment_artifact(
        readback=live, effective_records=effective if effective is not None else prepared['effective_export'],
        projection=projection if projection is not None else prepared['projection'],
        instances=instance_rows if instance_rows is not None else instances(),
        enrollment_links=links if links is not None else deepcopy(FIXTURE['enrollment_links']),
        legacy_roster=roster if roster is not None else legacy_roster(),
        observation_bindings=bindings if bindings is not None else observation_bindings(live),
        source=SOURCE, versions=versions or VERSIONS, prepared_at=CORPUS['observed_at'])


class SyntheticEnrollmentSource:
    """The protected enrollment source test peer: a selection and artifacts."""

    def __init__(self, artifact_bytes, *, versions=None, authenticated=True, source=SOURCE):
        self.artifacts = {}
        self.authenticated = authenticated
        self.source = source
        self.select(artifact_bytes, versions)
        self.selection_reads = 0
        self.artifact_reads = 0

    def select(self, artifact_bytes, versions=None):
        digest = hashlib.sha256(artifact_bytes).hexdigest()
        self.artifacts[digest] = artifact_bytes
        self.current = {'format': authority.SELECTION_FORMAT, 'source': SOURCE, **(versions or VERSIONS),
                        'artifact_sha256': digest}

    def read_selection(self):
        self.selection_reads += 1
        return authority.SourceRead(self.source, self.authenticated, body(self.current))

    def read_artifact(self, selection):
        self.artifact_reads += 1
        return authority.SourceRead(self.source, self.authenticated,
                                    self.artifacts.get(selection.artifact_sha256, b''))


def acquire(document, clock=None, **auth):
    client = authority.AcquisitionClient(BOOT, SyntheticAuth(**auth), SyntheticTransport(ok(document)))
    return client.acquire(clock or OBSERVED)


def selected(artifact_bytes, versions=None):
    source = SyntheticEnrollmentSource(artifact_bytes, versions=versions)
    selection = authority.read_selection(source.read_selection(), SOURCE)
    return authority.load_artifact(selection, source.read_artifact(selection))
